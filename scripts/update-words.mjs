import { access, mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";

const ESDB_REPOSITORY = "https://github.com/en-wl/wordlist.git";
const ESDB_REF = "rel-2026.02.25";
const ESDB_COMMIT = "7e99edab8e32f9f9ea2b15f249ca8d4d67237410";
const ESDB_SIZES = [35, 40, 50, 60, 65, 70, 80];
const OUTPUT_PATH = path.resolve(import.meta.dirname, "../src/data/words.js");

async function run(command, options = {}) {
  const process = Bun.spawn(command, {
    cwd: options.cwd,
    stdout: options.capture ? "pipe" : "inherit",
    stderr: options.capture ? "pipe" : "inherit",
  });

  const [exitCode, stdout, stderr] = await Promise.all([
    process.exited,
    options.capture ? new Response(process.stdout).text() : "",
    options.capture ? new Response(process.stderr).text() : "",
  ]);

  if (exitCode !== 0) {
    throw new Error(`${command.join(" ")} failed (${exitCode})\n${stderr}`);
  }

  return stdout;
}

async function prepareSource() {
  const suppliedSource = process.env.ESDB_SOURCE_DIR;
  if (suppliedSource) {
    return { directory: path.resolve(suppliedSource), temporaryRoot: null };
  }

  const temporaryRoot = await mkdtemp(path.join(tmpdir(), "wordle-esdb-"));
  const directory = path.join(temporaryRoot, "source");
  await run([
    "git",
    "clone",
    "--depth",
    "1",
    "--branch",
    ESDB_REF,
    ESDB_REPOSITORY,
    directory,
  ]);
  return { directory, temporaryRoot };
}

async function verifySource(directory) {
  const commit = (await run(["git", "rev-parse", "HEAD"], { cwd: directory, capture: true })).trim();
  if (commit !== ESDB_COMMIT) {
    throw new Error(`Expected ESDB commit ${ESDB_COMMIT}, received ${commit}.`);
  }

  try {
    await access(path.join(directory, "scowl.db"));
  } catch {
    console.log("Building the pinned ESDB database…");
    await run(["make"], { cwd: directory });
  }
}

async function extractWords(directory, size) {
  const output = await run(
    [
      "./scowl",
      "word-list",
      String(size),
      "A,B,Z",
      "5",
      "--deaccent",
      "--wo-poses=abbr",
    ],
    { cwd: directory, capture: true },
  );

  return output
    .split(/\r?\n/)
    .filter((word) => /^[a-z]{5}$/.test(word));
}

function buildGeneratedModule(entries) {
  const serializedEntries = entries
    .map(([word, commonness]) => `  ["${word}", ${commonness}],`)
    .join("\n");

  return `// This file is generated by \`bun run words:update\`. Do not edit manually.
// Source: ESDB ${ESDB_REF} (${ESDB_COMMIT})
// Configuration: size 80, A/B/Z spellings, variant level 5, deaccented, no abbreviations.

export const WORD_SOURCE = Object.freeze({
  name: "English Speller Database",
  ref: "${ESDB_REF}",
  commit: "${ESDB_COMMIT}",
  wordCount: ${entries.length},
  size: 80,
  spellings: "A/B/Z",
  variantLevel: 5,
});

export const WORD_ENTRIES = [
${serializedEntries}
];

export const wordCommonness = new Map(WORD_ENTRIES);

const words = WORD_ENTRIES.map(([word]) => word);

export default words;
`;
}

async function main() {
  const { directory, temporaryRoot } = await prepareSource();

  try {
    await verifySource(directory);
    const commonness = new Map();

    for (const size of ESDB_SIZES) {
      const extracted = await extractWords(directory, size);
      for (const word of extracted) {
        if (!commonness.has(word)) commonness.set(word, size);
      }
      console.log(`ESDB size ${size}: ${extracted.length.toLocaleString()} five-letter words`);
    }

    const entries = [...commonness.entries()].sort(([a], [b]) => a.localeCompare(b));
    const generated = buildGeneratedModule(entries);

    await Bun.write(OUTPUT_PATH, generated);
    console.log(`Generated ${entries.length.toLocaleString()} words at ${OUTPUT_PATH}`);
    console.log(`${entries.length.toLocaleString()} words · one pinned ESDB source · no supplemental merge`);
  } finally {
    if (temporaryRoot) await rm(temporaryRoot, { recursive: true, force: true });
  }
}

await main();
